import yaml from 'js-yaml';
import fs from 'fs/promises';

const { services } = yaml.load(await fs.readFile('registry.yml', 'utf8'));

const pluginLines = services.map((s) => `  [
    '@docusaurus/plugin-content-docs',
    {
      id: '${s.id}',
      path: 'content/${s.id}/${s.docs_path.replace(/\/$/, '')}',
      routeBasePath: '${s.id}',
      sidebarPath: undefined,
    },
  ]`).join(',\n');

const pluginConfig = `// auto-generated by scripts/generate-docusaurus-config.js — do not edit
const generatedPlugins = [\n${pluginLines},\n];\nexport default generatedPlugins;\n`;

const servicesMeta = services.map((s) => ({ id: s.id, label: s.label ?? s.id, routeBasePath: s.id }));

await fs.mkdir('generated', { recursive: true });
await fs.writeFile('generated/plugin-config.ts', pluginConfig);
await fs.writeFile('generated/services-meta.json', JSON.stringify(servicesMeta, null, 2));
console.log(`[gen-config] ${services.length} service(s) → generated/plugin-config.ts`);
